"""Phase 5 exit check runner (D-29; generation design, section 11).

    .venv\\Scripts\\python eval\\generation\\run_exit_check.py --run 1

Runs the 15 exit-check questions (10 dev questions, by id, plus G01 to G05) through `generate()`
once and writes:

- eval/generation/results/exit_check_run<N>.json (committed): per question the status, claims
  with their cited chunk ids, gaps, passages, disclosures (hidden ones included), the rendered
  answer, usage, cost and log record id. Dev questions are named by id only, as in the Phase 4
  result files.
- docs/phase05_generation/review_pack/run<N>/ (git-ignored): review_sheet.md, which puts each
  answer next to the full text of every retrieved chunk, and a results template with one row per
  claim for the reviewers.

Every call is also logged in full under logs/generation/ (D-28). The test split is never loaded:
dev questions come from run_eval.load_questions("dev"), which drops test rows unread. Query
vectors come from the Phase 4 query cache, so dev questions retrieve exactly what the dev
evaluation retrieved. A run number is never overwritten.
"""
from __future__ import annotations

import argparse
import csv
import importlib.util
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "python"))

from check_pgvector import connect  # noqa: E402
from generation.disclosure import load_policy  # noqa: E402
from generation.generate import DbCorpusStore, generate, retrieval_config  # noqa: E402
from generation.llm import AnthropicLLMClient, cost_usd  # noqa: E402
from retrieval.retrieve import Retriever  # noqa: E402

spec = importlib.util.spec_from_file_location("run_eval", ROOT / "eval" / "retrieval" / "run_eval.py")
run_eval = importlib.util.module_from_spec(spec)
sys.modules.setdefault("run_eval", run_eval)
spec.loader.exec_module(run_eval)

QUESTIONS = HERE / "exit_questions.jsonl"
RESULTS_DIR = HERE / "results"
PACK_DIR = ROOT / "docs" / "phase05_generation" / "review_pack"
USAGE_KEYS = ("input_tokens", "output_tokens", "cache_creation_input_tokens", "cache_read_input_tokens")


def load_exit_questions(path: Path = QUESTIONS) -> list[dict]:
    """Exit questions with their text: dev text by id from the dev split, new text from the file."""
    dev = {q["id"]: q for q in run_eval.load_questions("dev")}
    rows = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    for row in rows:
        if row["source"] == "questions_v1":
            if row["id"] not in dev:
                raise ValueError(f"{row['id']} is not a dev question")
            row["question"] = dev[row["id"]]["question"]
    return rows


def answer_row(spec_row: dict, answer) -> dict:
    row = {"id": spec_row["id"], "source": spec_row["source"], "expected": spec_row["expected"],
           "checks": spec_row["checks"]}
    if spec_row["source"] == "new":
        row["question"] = spec_row["question"]
    row.update({
        "status": answer.status,
        "claims": [{"no": i, "text": c.text, "labels": c.labels, "chunk_ids": c.chunk_ids}
                   for i, c in enumerate(answer.claims, 1)],
        "gaps": answer.gaps,
        "passages": [{"label": p.label, "rank": p.rank, "chunk_id": p.chunk_id, "citation": p.citation}
                     for p in answer.passages],
        "cited_chunk_ids": answer.cited_chunk_ids,
        "rejected_citations": answer.rejected_citations,
        "disclosures": [{"kind": d.kind, "ref": d.ref, "applies_to": d.applies_to, "reason": d.reason,
                         "merged": d.merged} for d in answer.disclosures],
        "rendered": answer.rendered,
        "usage": answer.usage,
        "cost_usd": round(answer.cost_usd, 6),
        "record_id": answer.record_id,
        "error": answer.error,
    })
    return row


def review_sheet(run: int, rows: list[dict], questions: dict[str, str], chunk_text: dict[str, dict]) -> str:
    out = [f"# Phase 5 exit check, run {run}: review sheet", "",
           "Generated by eval/generation/run_exit_check.py (git-ignored). For each question, check every "
           "claim against the full text of the chunks it cites (below the answer), then the declines, "
           "the no-arithmetic rule, the disclosures and the disclaimer (design section 11.3). Record "
           "verdicts in the results template next to this file.", ""]
    for row in rows:
        out += [f"## {row['id']} ({row['source']}, expected {row['expected']})", "",
                f"**Question:** {questions[row['id']]}", "", f"**Checks:** {row['checks']}", "",
                f"**Status:** {row['status']}" + (f" (error: {row['error']})" if row["error"] else ""), "",
                "### Rendered answer", "", "````text", row["rendered"], "````", ""]
        if row["claims"]:
            out += ["### Claims", "", "| No. | Claim | Cited |", "|---|---|---|"]
            out += [f"| {c['no']} | {c['text']} | {', '.join(c['chunk_ids'])} |" for c in row["claims"]]
            out.append("")
        if row["rejected_citations"]:
            out += ["**Rejected citations:** " + json.dumps(row["rejected_citations"]), ""]
        hidden = [d["ref"] for d in row["disclosures"] if d["kind"] == "hidden"]
        if hidden:
            out += [f"**Hidden register rows (logged, not rendered):** {', '.join(hidden)}", ""]
        out += ["### Retrieved passages", ""]
        for p in row["passages"]:
            mark = " (cited)" if p["chunk_id"] in row["cited_chunk_ids"] else ""
            out += [f"**{p['label']}{mark}** `{p['chunk_id']}`, {p['citation']}", "", "````text",
                    chunk_text[p["chunk_id"]]["text"], "````", ""]
    return "\n".join(out)


def write_template(path: Path, run: int, rows: list[dict]) -> None:
    with path.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(["run", "question_id", "claim_no", "claim_text", "cited_chunk_ids", "verdict",
                         "reviewer", "confirmed_by_owner", "note"])
        for row in rows:
            writer.writerow([run, row["id"], 0, f"status {row['status']}; disclosures and disclaimer", "", "",
                             "", "", ""])
            for c in row["claims"]:
                writer.writerow([run, row["id"], c["no"], c["text"], " ".join(c["chunk_ids"]), "", "", "", ""])


def run(run_no: int) -> dict:
    out_path = RESULTS_DIR / f"exit_check_run{run_no}.json"
    if out_path.exists():
        raise SystemExit(f"{out_path.name} already exists; use the next run number")
    specs = load_exit_questions()
    config = retrieval_config()
    cache = run_eval.QueryCache(config["model"])
    policy = load_policy()
    llm = AnthropicLLMClient()
    rows = []
    with connect() as conn:
        retriever, store = Retriever(conn, config), DbCorpusStore(conn)
        for spec_row in specs:
            vector = cache.embed(spec_row["question"])
            answer = generate(spec_row["question"], retriever=retriever, llm=llm, store=store,
                              query_vector=vector, policy=policy)
            rows.append(answer_row(spec_row, answer))
            print(f"{spec_row['id']}: {answer.status}, {len(answer.claims)} claims, "
                  f"{answer.usage['input_tokens']}+{answer.usage['cache_read_input_tokens']} cached in, "
                  f"{answer.usage['output_tokens']} out, ${answer.cost_usd:.4f}")
        chunk_text = store.chunks(sorted({p["chunk_id"] for r in rows for p in r["passages"]}))

    totals = {key: sum(r["usage"][key] for r in rows) for key in USAGE_KEYS}
    record = {"run": run_no, "run_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
              "model": llm.model, "retrieval_config_sha256": run_eval.FINAL_CONFIG_SHA256,
              "questions_file": QUESTIONS.relative_to(ROOT).as_posix(),
              "query_embeddings": {"from_cache": cache.hits, "embedded": cache.misses, "tokens": cache.tokens_used},
              "totals": {"usage": totals, "cost_usd": round(cost_usd(totals, llm.model), 6),
                         "cost_per_question_usd": round(cost_usd(totals, llm.model) / len(rows), 6)},
              "review": "pending", "questions": rows}
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    with out_path.open("x", encoding="utf-8", newline="\n") as fh:
        json.dump(record, fh, ensure_ascii=False, indent=1)
        fh.write("\n")

    pack = PACK_DIR / f"run{run_no}"
    pack.mkdir(parents=True, exist_ok=True)
    texts = {s["id"]: s["question"] for s in specs}
    (pack / "review_sheet.md").write_text(review_sheet(run_no, rows, texts, chunk_text), encoding="utf-8")
    write_template(pack / "exit_check_results_template.csv", run_no, rows)
    return record


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--run", type=int, required=True, help="run number (never overwritten)")
    args = parser.parse_args(argv)
    record = run(args.run)
    t = record["totals"]
    print(f"run {record['run']}: {len(record['questions'])} questions, usage {t['usage']}, "
          f"total ${t['cost_usd']:.4f}, per question ${t['cost_per_question_usd']:.4f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
